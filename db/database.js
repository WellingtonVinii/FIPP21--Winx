import mysql from 'mysql2'

//um único pool para a aplicação inteira: cada repositório instancia um Database e, se cada um
//abrisse o seu próprio pool, as conexões se acumulariam até estourar o max_connections do MySQL
const pool = mysql.createPool({
    host: '129.148.37.133',
    database: 'BancoDeDados',
    user: 'wellington',
    password: 'Nicolas2019?',
    connectionLimit: 10,    //o servidor do banco é compartilhado (limite de 200 conexões para todos)
    maxIdle: 2,             //conexões ociosas além dessas são fechadas após o idleTimeout
    idleTimeout: 30000
});

export default class Database {

    #conexao;

    get conexao() { return this.#conexao;} set conexao(conexao) { this.#conexao = conexao; }

    constructor() {
        this.#conexao = pool;
    }

    AbreTransacao() {
        var cnn = this.#conexao;
        return new Promise(function(res, rej) {
            cnn.query("START TRANSACTION", function (error, results, fields) {
                if (error) 
                    rej(error);
                else
                    res(results);
            });
        })
    }
    
    Rollback() {
        var cnn = this.#conexao;
        return new Promise(function(res, rej) {
            cnn.query("ROLLBACK", function (error, results, fields) {
                if (error) 
                    rej(error);
                else
                    res(results);
            });
        })
    }
    
    Commit() {
        var cnn = this.#conexao;
        return new Promise(function(res, rej) {
            cnn.query("COMMIT", function (error, results, fields) {
                if (error) 
                    rej(error);
                else
                    res(results);
            });
        })
    }

    ExecutaComando(sql, valores) {
        var cnn = this.#conexao;
        return new Promise(function(res, rej) {
            cnn.query(sql, valores, function (error, results, fields) {
                if (error) 
                    rej(error);
                else 
                    res(results);
            });
        })
    }
    
    ExecutaComandoNonQuery(sql, valores) {
        var cnn = this.#conexao;
        return new Promise(function(res, rej) {
            cnn.query(sql, valores, function (error, results, fields) {
                if (error) 
                    rej(error);
                else 
                    res(results.affectedRows > 0);
            });
        })
    }

    ExecutaComandoLastInserted(sql, valores) {
        var cnn = this.#conexao;
        return new Promise(function(res, rej) {
            cnn.query(sql, valores, function (error, results, fields) {
                if (error) 
                    rej(error);
                else 
                    res(results.insertId);
            });
        })
    }

}


